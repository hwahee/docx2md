/**
 * Bringing the Markdown mirror in line with the sources.
 *
 * Work is split into planning (what would change — pure reads) and applying
 * (the writes), so `check` and `build` share every decision and differ only in
 * whether the plan is carried out.
 *
 * Safety rule: a Markdown file is only ever overwritten or deleted when its
 * header says docx2md generated it, and an assets folder only ever loses files
 * whose names are content hashes. Hand-written files are never touched.
 */
import { mkdir, rm, rmdir, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';

import type { Options } from './config';
import { ASSET_NAME, convertDocx } from './convert';
import {
  assetsOf,
  FORMAT_VERSION,
  header,
  HEADER_BYTES,
  outputsFor,
  parseHeader,
  type Generated,
} from './layout';
import { sourceMatcher, walk } from './sources';

type Change =
  | { readonly kind: 'write'; readonly path: string; readonly data: string | Uint8Array }
  | { readonly kind: 'delete'; readonly path: string };

/** What happened (or, for `check`, would happen) to one source. */
export type Outcome =
  | {
      readonly kind: 'updated';
      readonly source: string;
      readonly changes: readonly Change[];
      /** Set when the previous Markdown was written by another output format (a tool update). */
      readonly previousFormat?: number;
    }
  | { readonly kind: 'removed'; readonly source: string; readonly changes: readonly Change[] }
  | { readonly kind: 'failed'; readonly source: string; readonly message: string };

export interface SyncOptions {
  /** `false` plans only — nothing on disk changes (`check`). */
  readonly write: boolean;
  /**
   * Skips sources whose size and mtime match the last successful sync — for
   * `watch`, which re-syncs on every file event. Updated in place.
   */
  readonly seen?: Map<string, string>;
}

/** Converts every selected source and removes generated files whose source is gone. */
export async function syncAll(
  root: string,
  options: Options,
  sync: SyncOptions,
): Promise<Outcome[]> {
  const files = await walk(root);
  const isSource = sourceMatcher(options);
  const sources = files.filter(isSource);
  const outcomes: Outcome[] = [];

  for (const source of sources) {
    const signature = await signatureOf(join(root, source));
    if (signature !== undefined && sync.seen?.get(source) === signature) continue;
    const outcome = await syncSource(
      root,
      options,
      source,
      await Bun.file(join(root, source)).bytes(),
      sync.write,
    );
    if (outcome?.kind === 'failed') sync.seen?.delete(source);
    else if (signature !== undefined) sync.seen?.set(source, signature);
    if (outcome !== undefined) outcomes.push(outcome);
  }

  const current = new Set(sources);
  for (const key of sync.seen?.keys() ?? []) if (!current.has(key)) sync.seen?.delete(key);
  for (const markdown of files.filter((file) => file.endsWith('.md'))) {
    const source = (await generatedFrom(root, markdown))?.source;
    if (source === undefined) continue;
    // Orphaned: the source is gone or no longer selected, or outDir moved its output elsewhere.
    if (current.has(source) && outputsFor(source, options.outDir).markdown === markdown) continue;
    outcomes.push(await removeMarkdown(root, source, markdown, sync.write));
  }
  return outcomes;
}

/**
 * Converts one source from the given bytes (the working tree's, or the git
 * index's for `staged`). `undefined` means its outputs were already current.
 */
export async function syncSource(
  root: string,
  options: Options,
  source: string,
  data: Uint8Array,
  write: boolean,
): Promise<Outcome | undefined> {
  const outputs = outputsFor(source, options.outDir);
  try {
    const existing = await generatedFrom(root, outputs.markdown);
    if (existing === undefined && (await Bun.file(join(root, outputs.markdown)).exists())) {
      throw new Error(
        `${outputs.markdown} exists and was not generated by docx2md; refusing to overwrite it`,
      );
    }
    if (existing !== undefined && existing.source !== source) {
      throw new Error(
        `${outputs.markdown} was generated from ${existing.source}; refusing to overwrite it`,
      );
    }

    const { markdown, assets } = await convertDocx(data, {
      images: options.images,
      assetsLink: outputs.assetsLink,
    });
    const text = markdown === '' ? header(source) : `${header(source)}\n${markdown}`;

    const changes: Change[] = [];
    if ((await readText(join(root, outputs.markdown))) !== text) {
      changes.push({ kind: 'write', path: outputs.markdown, data: text });
    }
    // Asset names are content hashes: an existing file with the name already has the bytes.
    const wanted = new Set(assets.map((asset) => asset.name));
    const present = await assetFiles(root, outputs.assets);
    for (const asset of assets) {
      if (!present.includes(asset.name)) {
        changes.push({ kind: 'write', path: `${outputs.assets}/${asset.name}`, data: asset.data });
      }
    }
    for (const name of present) {
      if (!wanted.has(name)) changes.push({ kind: 'delete', path: `${outputs.assets}/${name}` });
    }

    if (changes.length === 0) return undefined;
    if (write) await apply(root, changes);
    return existing !== undefined && existing.format !== FORMAT_VERSION
      ? { kind: 'updated', source, changes, previousFormat: existing.format }
      : { kind: 'updated', source, changes };
  } catch (error) {
    return {
      kind: 'failed',
      source,
      message: error instanceof Error ? error.message : String(error),
    };
  }
}

/** Removes the outputs of a source that is gone, if they exist and are ours. */
export async function removeSource(
  root: string,
  options: Options,
  source: string,
  write: boolean,
): Promise<Outcome | undefined> {
  const { markdown } = outputsFor(source, options.outDir);
  if ((await generatedFrom(root, markdown))?.source !== source) return undefined;
  return removeMarkdown(root, source, markdown, write);
}

async function removeMarkdown(
  root: string,
  source: string,
  markdown: string,
  write: boolean,
): Promise<Outcome> {
  const assets = assetsOf(markdown);
  const changes: Change[] = [
    { kind: 'delete', path: markdown },
    ...(await assetFiles(root, assets)).map((name) => ({
      kind: 'delete' as const,
      path: `${assets}/${name}`,
    })),
  ];
  if (write) await apply(root, changes);
  return { kind: 'removed', source, changes };
}

async function apply(root: string, changes: readonly Change[]): Promise<void> {
  for (const change of changes) {
    const path = join(root, change.path);
    if (change.kind === 'write') {
      await mkdir(dirname(path), { recursive: true });
      await Bun.write(path, change.data);
    } else {
      await rm(path, { force: true });
      // An assets folder that lost its last image goes too; anything else in it keeps it.
      if (dirname(change.path).endsWith('.assets')) {
        await rmdir(dirname(path)).catch(() => undefined);
      }
    }
  }
}

/** What a Markdown file's header says; `undefined` if absent or hand-written. */
async function generatedFrom(root: string, markdown: string): Promise<Generated | undefined> {
  const file = Bun.file(join(root, markdown));
  if (!(await file.exists())) return undefined;
  return parseHeader(await file.slice(0, HEADER_BYTES).text());
}

async function readText(path: string): Promise<string | undefined> {
  const file = Bun.file(path);
  return (await file.exists()) ? file.text() : undefined;
}

async function assetFiles(root: string, assets: string): Promise<string[]> {
  const glob = new Bun.Glob('*');
  const names: string[] = [];
  try {
    for await (const name of glob.scan({ cwd: join(root, assets), onlyFiles: true })) {
      if (ASSET_NAME.test(name)) names.push(name);
    }
  } catch {
    return []; // no assets folder
  }
  return names.sort();
}

async function signatureOf(path: string): Promise<string | undefined> {
  try {
    const info = await stat(path);
    return `${info.size}:${info.mtimeMs}`;
  } catch {
    return undefined;
  }
}
